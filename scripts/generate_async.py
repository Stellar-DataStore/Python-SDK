"""Generates src/stellards/_async/resources.py from src/stellards/_sync/resources.py.

The sync resources are the single source of every API call; the async ones are the same code with ``async`` /
``await`` added. Run ``python scripts/generate_async.py`` after changing the sync file (``--check`` only reports
whether the generated file is current; the test suite runs that check too).

Rules the sync file follows so this stays a handful of substitutions:
- every public method of a resource class (name not starting with "_") makes requests, so it becomes ``async def``;
- private methods and module-level functions are pure helpers, except ``_request``;
- a method calls the API only through ``self._request(...)``, ``self._core.request(...)``,
  ``self._core.refresh(...)`` or another public method ``self.name(...)``.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "stellards" / "_sync" / "resources.py"
TARGET = ROOT / "src" / "stellards" / "_async" / "resources.py"

HEADER = "# This file is generated by scripts/generate_async.py from stellards/_sync/resources.py. Do not edit it.\n"

_PUBLIC_METHOD = re.compile(r"^(    )def (?!_)(\w+)\(")
_REQUEST_METHOD = re.compile(r"^(    )def _request\(")


def _asyncify_methods(text: str) -> str:
    lines = []
    in_class = False
    for line in text.split("\n"):
        # A top-level statement starts a new block: a class, or something else (functions, assignments, ...).
        if line and not line[0].isspace() and not line.startswith(("#", ")", "]", "}", "@")):
            in_class = line.startswith("class ")
        if in_class:
            line = _PUBLIC_METHOD.sub(r"\1async def \2(", line)
            line = _REQUEST_METHOD.sub(r"\1async def _request(", line)
        lines.append(line)
    return "\n".join(lines)


def generate(source: str) -> str:
    text = source
    text = text.replace(
        '"""The resource groups of the synchronous client.', '"""The resource groups of the asynchronous client.', 1
    )
    text = text.replace(
        "from .._core import ApiRequest, ProjectId, SyncCore", "from .._core import ApiRequest, AsyncCore, ProjectId"
    )
    text = text.replace("SyncCore", "AsyncCore")
    text = text.replace(
        "from collections.abc import Iterable, Iterator,", "from collections.abc import AsyncIterator, Iterable,"
    )
    text = re.sub(r"\bIterator\[", "AsyncIterator[", text)
    text = _asyncify_methods(text)
    # Calls that do I/O get awaited.
    text = re.sub(r"(?<!await )self\._request\(", "await self._request(", text)
    text = re.sub(r"(?<!await )self\._core\.request\(", "await self._core.request(", text)
    text = re.sub(r"(?<!await )self\._core\.refresh\(", "await self._core.refresh(", text)
    text = re.sub(r"(?<!await )\bself\.(?!_)(\w+)\(", r"await self.\1(", text)
    return HEADER + text


def main() -> int:
    expected = generate(SOURCE.read_text(encoding="utf-8"))
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != expected:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python scripts/generate_async.py")
            return 1
        return 0
    with TARGET.open("w", encoding="utf-8", newline="\n") as file:  # LF on every OS
        file.write(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
